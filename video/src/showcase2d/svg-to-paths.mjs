// Turns a logo SVG (potrace / Inkscape / Illustrator export) into the path module LogoDraw reads.
// Usage (from video/): node src/showcase2d/svg-to-paths.mjs public/logo-white.svg > src/showcase2d/logoPaths.ts
import fs from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('usage: node svg-to-paths.mjs <logo.svg>');
  process.exit(1);
}
const svg = fs.readFileSync(file, 'utf8');
const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]?.trim().split(/[\s,]+/).map(Number) ?? [0, 0, 1000, 1000];
const transform = svg.match(/<g[^>]*\stransform="([^"]+)"/)?.[1] ?? '';
const scale = Math.abs(Number(transform.match(/scale\(\s*([-\d.]+)/)?.[1] ?? 1));
const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, ' ').trim());
if (paths.length === 0) {
  console.error(`no <path d="..."> found in ${file}`);
  process.exit(1);
}

const out = `// Generated by svg-to-paths.mjs from ${file.split('/').pop()} — regenerate instead of editing by hand.
export const logoPaths = {
  viewBox: ${JSON.stringify(viewBox.join(' '))},
  // <g transform> copied from the source (potrace: 10x units, flipped y). Empty when the SVG has none.
  transform: ${JSON.stringify(transform.replace(/\s+/g, ' '))},
  // Path units -> viewBox units, used to keep stroke widths in screen pixels.
  scale: ${scale},
  width: ${viewBox[2]},
  height: ${viewBox[3]},
  paths: [
${paths.map((d) => `    ${JSON.stringify(d)},`).join('\n')}
  ],
} as const;
`;
process.stdout.write(out);
